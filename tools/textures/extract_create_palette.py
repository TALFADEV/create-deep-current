"""Derives colour ramps from Create's own textures, so our art sits in Create's art direction.

Usage:
    python tools/textures/extract_create_palette.py [path/to/create.jar]

Without an argument, the Create jar is looked up in the Gradle cache. Writes palette_create.py (colour values
only: no Create asset is copied into the mod).
"""

from __future__ import annotations

import io
import os
import sys
import zipfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "palette_create.py"
STEPS = 6

# Ramp name -> (texture in Create's jar, region to sample: "all", "frame" (2-px border) or "inner").
SOURCES = {
    "BRASS": ("block/brass_block", "all"),
    "COPPER": ("block/fluid_tank", "all"),
    "ANDESITE": ("block/andesite_casing", "frame"),
    "DARK_WOOD": ("block/brass_casing", "inner"),
    "IRON": ("block/bracket_plate_metal", "all"),
    "RUBBER": ("block/belt", "all"),
    "CREATIVE_FRAME": ("block/creative_casing", "frame"),
    "CREATIVE_INNER": ("block/creative_casing", "inner"),
}


def find_jar() -> Path:
    homes = [os.environ.get("GRADLE_USER_HOME"), str(Path.home() / ".gradle")]
    for home in filter(None, homes):
        cache = Path(home) / "caches" / "modules-2" / "files-2.1" / "com.simibubi.create"
        jars = sorted(cache.glob("create-*/*/*/create-*.jar")) if cache.exists() else []
        if jars:
            return jars[-1]
    sys.exit("Create jar not found; pass its path as an argument")


def pixels(img: Image.Image, region: str) -> list[tuple[int, int, int]]:
    img = img.convert("RGBA").crop((0, 0, 16, 16))
    result = []
    for y in range(16):
        for x in range(16):
            frame = x < 2 or y < 2 or x > 13 or y > 13
            if region == "frame" and not frame or region == "inner" and frame:
                continue
            r, g, b, a = img.getpixel((x, y))
            if a > 0:
                result.append((r, g, b))
    return result


def luminance(c: tuple[int, int, int]) -> float:
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ramp(colors: list[tuple[int, int, int]]) -> list[str]:
    """STEPS colours from darkest to lightest: the mean of each luminance slice."""
    colors = sorted(colors, key=luminance)
    out = []
    for i in range(STEPS):
        chunk = colors[i * len(colors) // STEPS:(i + 1) * len(colors) // STEPS] or [colors[-1]]
        mean = tuple(round(sum(c[k] for c in chunk) / len(chunk)) for k in range(3))
        out.append("#%02X%02X%02X" % mean)
    return out


def main() -> None:
    jar = Path(sys.argv[1]) if len(sys.argv) > 1 else find_jar()
    lines = [f'"""Colour ramps sampled from Create\'s textures ({jar.name}). Generated by extract_create_palette.py."""',
             "", "RAMPS = {"]
    with zipfile.ZipFile(jar) as archive:
        for name, (texture, region) in SOURCES.items():
            data = archive.read(f"assets/create/textures/{texture}.png")
            values = ramp(pixels(Image.open(io.BytesIO(data)), region))
            lines.append(f'    "{name}": {values!r},')
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.name} from {jar.name}")


if __name__ == "__main__":
    main()
