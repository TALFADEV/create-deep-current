"""Shared colour palette for every Deep Current texture.

Metals, wood, rubber and the creative casing come straight from Create's textures (palette_create.py,
regenerated by extract_create_palette.py), so our blocks sit next to Create's without clashing. The few colours
Create lacks (patina, glazed ceramic, voltage markings, sea) are muted to the same warmth and saturation.

Each ramp goes from darkest to lightest. Never hard-code a colour in a generator: add it here instead.
"""

from __future__ import annotations

from palette_create import RAMPS as CREATE
from palette_refs import RAMPS as REFS


def rgb(hex_code: str) -> tuple[int, int, int, int]:
    """'#RRGGBB' -> (r, g, b, 255)."""
    h = hex_code.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255


def ramp(*hex_codes: str) -> list[tuple[int, int, int, int]]:
    return [rgb(h) for h in hex_codes]


TRANSPARENT = (0, 0, 0, 0)

# --- From Create -------------------------------------------------------------------------------
BRASS = ramp(*CREATE["BRASS"])
COPPER = ramp(*CREATE["COPPER"])
ANDESITE = ramp(*CREATE["ANDESITE"])
